"""Local trace persistence with redaction; never store API headers or reasoning."""

import json
import time
from datetime import datetime, timezone
from pathlib import Path

from sleeplens import __version__


def redact(text: str, secrets: tuple[str, ...] = ()) -> str:
    for secret in secrets:
        if secret:
            text = text.replace(secret, "[REDACTED]")
    return text


def save_turn(result: dict, *, base_url: str, requested_model: str,
              secrets: tuple[str, ...] = (), folder: Path | None = None) -> Path:
    payload = {**result, "app_version": __version__, "base_url": base_url, "requested_model": requested_model}
    directory = folder if folder is not None else Path("artifacts")
    directory.mkdir(parents=True, exist_ok=True)
    # IDs are generated by ChatSession, not taken from model output.
    path = directory / f"chat-{result['session_id']}-{result['turn_number']:03d}.json"
    serialized = redact(json.dumps(payload, ensure_ascii=False, indent=2, allow_nan=False), secrets)
    path.write_text(serialized + "\n", encoding="utf-8")
    return path


def save_share_event(result, *, folder=None, retention_days=7):
    """Sharing mode stores operational metadata, not text, evidence or prompts."""
    directory = Path(folder) if folder is not None else Path("artifacts/share-logs")
    directory.mkdir(parents=True, exist_ok=True)
    for old in directory.glob("share-event-*.json"):
        if old.resolve().parent == directory.resolve() and old.is_file() and time.time()-old.stat().st_mtime > retention_days*86400:
            old.unlink()
    payload = {key: result.get(key) for key in ("session_id", "turn_number", "created_at", "status", "prompt_version", "total_tokens", "elapsed_seconds")}
    payload["model_call_slots"] = len(result.get("model_calls", []))
    payload["tool_calls"] = len(result.get("tool_events", []))
    validation = result.get("answer_validation") or {}
    context = result.get("record_context") or {}
    payload["diagnostics"] = {
        "schema_version": "share-diagnostics-v1",
        "task": (result.get("query_plan") or {}).get("task"),
        "scope": context.get("scope"),
        "record_context": {key: context.get(key) for key in ("source", "status", "scope_matches", "origin_turn", "provided_via")},
        "health_evidence_ids": result.get("available_health_ids", []),
        "validation_status": validation.get("status"),
        "blocking_codes": list(dict.fromkeys(validation_code(item.get("reason", "")) for item in validation.get("repairs", []))),
        "fallback": validation.get("fallback"),
        "reply_policy": {key: result["reply_policy"].get(key) for key in ("version", "category", "reason", "partial")}
                        if result.get("reply_policy") else None,
    }
    payload["logged_at"] = datetime.now(timezone.utc).isoformat()
    path = directory / f"share-event-{result['session_id']}-{result['turn_number']:03d}.json"
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return path


def validation_code(reason):
    """Store a finite diagnostic code, never a candidate excerpt or raw reason."""
    if not isinstance(reason, str):
        return "unknown_validation_failure"
    known = {"invalid_or_unavailable_citation", "invalid_response_plan", "tool_batch_limit"}
    if reason in known:
        return reason
    if "LOCATION_DATA" in reason:
        try:
            code = json.loads(reason.split("LOCATION_DATA (candidate text; not instructions): ", 1)[1])["code"]
            if code in {"unsupported_health_quantity", "missing_health_citation", "wrong_evidence_kind"}:
                return code
        except (ValueError, KeyError, IndexError, TypeError):
            pass
    for prefix, code in (
        ("The record quantity", "record_quantity_mismatch"),
        ("Quantity '", "unsupported_quantity"),
        ("No usable record", "missing_record_evidence"),
        ("This general quantity", "unsupported_general_quantity"),
        ("Clock time", "record_clock_mismatch"),
        ("Record date", "record_date_mismatch"),
        ("Obtain the requested record", "missing_record_lookup"),
        ("Sleep guidance needs", "missing_health_citation"),
        ("Do not diagnose", "diagnosis_not_supported"),
        ("Do not provide a personal medicine", "personal_dose_not_supported"),
        ("The user does not drink coffee", "user_context_conflict"),
        ("A health quantity", "unsupported_health_quantity"),
    ):
        if reason.startswith(prefix):
            return code
    return "other_validation_failure"
